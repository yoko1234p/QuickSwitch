#!/usr/bin/env python3
"""Generate static per-project catalogs; no network or runtime translation dependency."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROJECTS = {
    "BarPilot": "BarPilotCore", "DeskTools": "DeskCore", "NotchHub": "NotchHub",
    "QuickSwitch": "QuickSwitchCore", "SelectionBar": "SelectionBarCore", "SuperPilot": "SuperPilotCore",
}
LANGUAGES = ("en", "zh-Hant", "zh-Hans")
PLACEHOLDERS = re.compile(r"%[1-9][0-9]*\$@")
CHINESE = re.compile(r"[\u4e00-\u9fff]")


def strings(table):
    return "/* Fixed interface text; user content and stable identifiers are not translated. */\n" + "".join(
        f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};\n"
        for key, value in sorted(table.items())
    )


def restore_spacing(key, value):
    prefix = re.match(r"^\s*", key)[0]
    suffix = re.search(r"\s*$", key)[0]
    return prefix + value.strip() + suffix


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--records", type=Path, required=True)
    parser.add_argument("--english", type=Path, required=True)
    parser.add_argument("--simplified", type=Path, required=True)
    parser.add_argument("--allow-drafts", action="store_true")
    args = parser.parse_args()
    records = json.loads(args.records.read_text())
    english = json.loads(args.english.read_text())
    english.update(json.loads(Path(__file__).with_name("english-overrides.json").read_text()))
    simplified = json.loads(args.simplified.read_text())
    contexts = json.loads(Path(__file__).with_name("context-overrides.json").read_text())
    keys = {name: set() for name in (*PROJECTS, "TGLocal")}
    for record in records:
        project = record["file"].split("/")[0]
        if project in keys:
            keys[project].add(record["key"])
    for project, extra in contexts.items():
        keys[project].update(extra)
    missing, mismatches = [], []
    tables = {}
    for project, project_keys in keys.items():
        tables[project] = {language: {} for language in LANGUAGES}
        for key in sorted(project_keys):
            translated = contexts.get(project, {}).get(key, {}).get("en", english.get(key))
            if not translated:
                missing.append((project, key))
                translated = key
            elif sorted(PLACEHOLDERS.findall(key)) != sorted(PLACEHOLDERS.findall(translated)):
                mismatches.append((project, key, translated))
                translated = key
            values = {"en": restore_spacing(key, translated), "zh-Hant": key,
                      "zh-Hans": simplified.get(key, key)}
            values.update(contexts.get(project, {}).get(key, {}))
            # Match Simplified Chinese macOS terminology across generated and reviewed entries.
            for source, target in (("设定", "设置"), ("捷径", "快捷指令"), ("私隐", "隐私")):
                values["zh-Hans"] = values["zh-Hans"].replace(source, target)
            for language, value in values.items():
                tables[project][language][key] = value
    report = {"counts": {name: len(value) for name, value in keys.items()},
              "missing": missing, "placeholder_mismatches": mismatches}
    report_file = ROOT / ".build/localization/coverage.json"
    report_file.parent.mkdir(parents=True, exist_ok=True)
    report_file.write_text(json.dumps(report, ensure_ascii=False, indent=2))
    if (missing or mismatches) and not args.allow_drafts:
        raise SystemExit(f"Incomplete catalogs: {len(missing)} missing, {len(mismatches)} placeholder mismatches")
    for project, module in PROJECTS.items():
        directory = ROOT / project / "Sources" / module / "Resources/Localization"
        for language, table in tables[project].items():
            filename = directory / (language + ".lproj") / "Localizable.strings"
            filename.parent.mkdir(parents=True, exist_ok=True)
            filename.write_text(strings(table))
    extension = ROOT / "TGLocal"
    for language, table in tables["TGLocal"].items():
        filename = extension / "locales" / (language + ".json")
        filename.parent.mkdir(parents=True, exist_ok=True)
        filename.write_text(json.dumps(table, ensure_ascii=False, indent=2) + "\n")
    javascript = "// SPDX-License-Identifier: GPL-3.0-only\n// Generated from locales/*.json. Do not edit this file directly.\n"
    javascript += "globalThis.TGLocalCatalogs = Object.freeze(" + json.dumps(tables["TGLocal"], ensure_ascii=False, indent=2) + ");\n"
    (extension / "src/locales.js").write_text(javascript)
    print(json.dumps({"counts": report["counts"], "missing": len(missing), "mismatches": len(mismatches)}))


if __name__ == "__main__":
    main()
